function t(key, vars) {
  const d = DICT[LANG] || DICT.fr;
  let s = d[key] ?? DICT.fr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v));
  return s;
}

function fmtNum(n) {
  try { return Number(n).toLocaleString(LOCALE[LANG] || 'fr-FR'); }
  catch (e) { return String(n); }
}

function fmtTime(ts) {
  if (!ts) return '';
  try { return new Date(ts * 1000).toLocaleTimeString(LOCALE[LANG] || 'fr-FR', { hour: '2-digit', minute: '2-digit' }); }
  catch (e) { return ''; }
}

