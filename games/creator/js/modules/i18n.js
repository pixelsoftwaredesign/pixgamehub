export function tErr(msg) {
  if (!msg || typeof msg !== 'string') return msg;
  if (ERR_MAP[msg]) return t(ERR_MAP[msg]);
  for (const [re, fn] of ERR_RE) { const m = msg.match(re); if (m) return fn(m); }
  return msg;
}

